const {contextBridge,ipcRenderer}=require('electron');
contextBridge.exposeInMainWorld('convee',{
 chooseFiles:()=>ipcRenderer.invoke('files:choose'),
 choosePdfFiles:()=>ipcRenderer.invoke('pdf:choose'),
 chooseImage:()=>ipcRenderer.invoke('image:choose'),
 previewImage:file=>ipcRenderer.invoke('image:preview',file),
 chooseFolder:()=>ipcRenderer.invoke('folder:choose'),
 scanDuplicates:folder=>ipcRenderer.invoke('duplicates:scan',folder),
 inspectImageMetadata:file=>ipcRenderer.invoke('image:metadata',file),
 exportImageWithoutMetadata:file=>ipcRenderer.invoke('image:strip-metadata',file),
 inspect:paths=>ipcRenderer.invoke('files:inspect',paths),
 formats:ext=>ipcRenderer.invoke('formats:list',ext),
 engines:()=>ipcRenderer.invoke('engines:status'),
 loadHistory:()=>ipcRenderer.invoke('history:load'),
 loadPreferences:()=>ipcRenderer.invoke('preferences:load'),
 savePreferences:value=>ipcRenderer.invoke('preferences:save',value),
 onPreferencesChanged:cb=>ipcRenderer.on('preferences:changed',(_,v)=>cb(v)),
 saveHistory:items=>ipcRenderer.invoke('history:save',items),
 convert:payload=>ipcRenderer.invoke('files:convert',payload),
 pdfOperation:payload=>ipcRenderer.invoke('pdf:operate',payload),
 watchFolders:()=>ipcRenderer.invoke('watch:list'),
 watchFolder:cfg=>ipcRenderer.invoke('watch:add',cfg),
 unwatchFolder:id=>ipcRenderer.invoke('watch:remove',id),
 reveal:p=>ipcRenderer.invoke('files:reveal',p),open:p=>ipcRenderer.invoke('files:open',p),
 onFilesChosen:cb=>ipcRenderer.on('files:chosen',(_,p)=>cb(p)),
 onOverlayDrop:cb=>ipcRenderer.on('overlay:dropped',(_,p)=>cb(p)),
 onOverlayResult:cb=>ipcRenderer.on('overlay:result',(_,r)=>cb(r)),
 overlayDrop:paths=>ipcRenderer.send('overlay:dropped',paths),
 overlayConvert:payload=>ipcRenderer.send('overlay:convert',payload),
 overlayClose:()=>ipcRenderer.send('overlay:close'),
 onOverlayState:cb=>ipcRenderer.on('overlay:state',(_,s)=>cb(s))
});
